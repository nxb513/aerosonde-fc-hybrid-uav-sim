function [X, names, groups] = e3_features(ctx, traj, fc)
%E3_FEATURES Ma tran dac trung cho cac ung vien tai mot thoi diem quyet dinh.
%   [X, names, groups] = E3_FEATURES(ctx, traj, fc)
%     ctx   boi canh luc quyet dinh (run_flight); traj (n x 3) [phi_max gamma_max Va];
%     fc    (n x 1) tan so cat EMS (0 = kien truc thu dong / EMS khac)
%   Nhom dac trung (de lam ablation):
%     cand    phi_max, gamma_max, Va, f_c                      (ung vien)
%     task    loai nhiem vu, sai lech huong, do cao con lai, sai lech ngang, do cong,
%             khoang cach toi diem chuyen chang, goc doi huong ke tiep
%     config  m, x_cg, SM, Jy, P_fc, co sieu tu, thu dong, Td    (A3)
%     wind    gio trung binh, he so nhieu, cos/sin huong gio so voi huong bay (A4)
%     state   Va, phi, gamma, alpha, muc dung lai 3 s gan nhat, P dong co
%     elec    SoC, nang luong sieu tu, P_FC, U_bus             (A11)
n = size(traj, 1);
c = ctx;
v = [c.task_type, c.e_chi, c.dh_rem, c.e_py, c.kappa, c.d_wp, c.turn_next, ...
     c.mass, c.x_cg, c.SM, c.Jy, c.P_fc, c.sc_use, c.passive, c.Td, ...
     c.W, c.turb, c.cos_rel, c.sin_rel, ...
     c.Va, c.phi, c.gamma, c.alpha, c.u_recent, c.P_el, ...
     c.soc, c.esc, c.P_fcbus, c.V_bus];
X = [traj, fc(:), repmat(v, n, 1)];
X(~isfinite(X)) = 0;
names = {'phi_max','gamma_max','Va_c','f_c', ...
         'task','e_chi','dh_rem','e_py','kappa','d_wp','turn_next', ...
         'mass','x_cg','SM','Jy','P_fc','sc_use','passive','Td', ...
         'W','turb','cos_rel','sin_rel', ...
         'Va','phi','gamma','alpha','u_recent','P_el', ...
         'soc','esc','P_fcbus','V_bus'};
groups = struct('cand', 1:4, 'task', 5:11, 'config', 12:19, 'wind', 20:23, ...
                'state', 24:29, 'elec', 30:33);
end
